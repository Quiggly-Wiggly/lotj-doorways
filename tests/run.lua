-- Behavioral tests run in a real Lua VM with mocked Mudlet boundaries.
local H = dofile('tests/harness.lua')
local eq, tests = H.equal, {}
local function test(name, fn) tests[#tests+1]={name=name,fn=fn} end
local function ready(options)
  local D, env=H.reset(options); env.room(100,'Test spaceport'); env.advance(0)
  return D,env
end
local function save(D,dir,steps,vnum)
  local ok,err=D.setRule(vnum or 100,'Test spaceport',dir,steps)
  assert(ok,err)
end
local function last(t) return t[#t] end

test('normalizes all ten short and full directions',function()
  local D=ready(); eq(#D.directions,10)
  for _,dir in ipairs(D.directions) do
    eq(D.normalizeDirection(dir.short),dir.short)
    eq(D.normalizeDirection('  '..dir.long:upper()..'  '),dir.short)
  end
  eq(D.normalizeDirection('north east'),nil); eq(D.normalizeDirection(nil),nil)
end)
test('parses exact commands and rejects empty or multiline steps',function()
  local D=ready()
  eq(D.parseSequence(' open ne ;; say Enter ;;ne '),{'open ne','say Enter','ne'})
  for _,text in ipairs({'','  ',';;ne','ne;;','open ne;;;;ne','say enter\nlook','say\0enter'}) do
    local result,err=D.parseSequence(text); assert(not result and err,text)
  end
end)
test('validates a single matching final movement',function()
  local D=ready()
  eq(D.validateSteps('NORTHEAST',{'open ne','Northeast'}),{'open ne','northeast'})
  eq(D.validateSteps('e',{'say east'}),{'say east'})
  for _,steps in ipairs({{'n'},{'e','say enter'},{'e','e'},{'open e;;e'},{''},{'say enter\rlook'}}) do
    local value,err=D.validateSteps('east',steps); assert(not value and err)
  end
  assert(not D.validateSteps('bad',{'look'}))
  assert(not D.validateSteps('e',{[1]='open e',[3]='e'}))
end)
