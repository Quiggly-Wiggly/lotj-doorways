-- Portable rule copies use map-level userdata; no live map or game is touched.
return function(test,H)
  local eq=H.equal
  local key='lotj-doorways.rules.v1'
  local sample='{"version":1,"enabled":false,"rules":[{"vnum":"900","name":"Unmapped station","direction":"nw","commands":["say exit"]}]}'
  local empty='{"version":1,"enabled":true,"rules":[]}'

  test('saving an unmapped room mirrors rules without creating rooms or sending commands',function()
    local D,env=H.reset({mapUserData={author='Existing map author'}})
    assert(D.setRule(900,'Unmapped station','nw',{'say exit'}))
    local data=fromJSON(assert(env.mapUserData[key]))
    eq(data.version,1); eq(data.enabled,true); eq(#data.rules,1)
    eq(data.rules[1],D.getRule(900,'nw')); eq(env.mapUserData.author,'Existing map author')
    eq(env.exits,{}); eq(env.sent,{})
    eq(fromJSON(H.read()),data)
  end)
  test('map metadata follows edits deletion and enabled state',function()
    local D,env=H.reset()
    assert(D.setRule(900,'Station','nw',{'say exit'}))
    assert(D.setRule(900,'Station','nw',{'open nw','nw'}))
    eq(fromJSON(env.mapUserData[key]).rules[1].commands,{'open nw','nw'})
    assert(D.setEnabled(false)); eq(fromJSON(env.mapUserData[key]).enabled,false)
    assert(D.removeRule(900,'nw')); eq(fromJSON(env.mapUserData[key]).rules,{})
    eq(env.sent,{})
  end)
  test('a profile without local storage recovers validated rules from its map',function()
    local D,env=H.reset({mapUserData={[key]=sample}})
    eq(D.getRule(900,'nw').commands,{'say exit'}); eq(D.isEnabled(),false)
    eq(D.storageExists,true); eq(fromJSON(H.read()).rules[1].vnum,'900')
    eq(env.sent,{})
  end)
  test('an intentionally empty local library wins over stale map rules',function()
    local D,env=H.reset({storage=empty,mapUserData={[key]=sample}})
    eq(D.listRules(true),{}); eq(D.isEnabled(),true)
    eq(fromJSON(env.mapUserData[key]).rules,{})
    eq(fromJSON(H.read()).rules,{})
  end)
  test('local rules win when a different map is loaded later',function()
    local D,env=H.reset()
    assert(D.setRule(900,'Current station','nw',{'push button'}))
    local before=H.read(); env.mapUserData[key]=sample
    assert(D.mapStorage.load())
    eq(D.getRule(900,'nw').commands,{'push button'})
    eq(fromJSON(env.mapUserData[key]).rules[1].commands,{'push button'})
    eq(H.read(),before); eq(D.isEnabled(),true)
  end)
  test('missing map metadata never creates an empty local file',function()
    local D,env=H.reset(); assert(D.mapStorage.load())
    eq(H.read(),nil); eq(D.storageExists,false); eq(env.mapUserData[key],nil)
    eq(env.mapWrites,0); eq(env.sent,{})
  end)
  test('invalid map data is preserved and never becomes a local rule',function()
    for _,text in ipairs({'{broken','{"version":99,"enabled":true,"rules":[]}',
        '{"version":1,"enabled":true,"rules":[{"vnum":"900","name":"Station","direction":"nw","commands":["north"]}]}'}) do
      local D,env=H.reset({mapUserData={[key]=text}})
      eq(D.listRules(true),{}); eq(H.read(),nil); eq(env.mapUserData[key],text)
      local messages=#env.messages
      local ok,err=D.mapStorage.load(); assert(not ok and err)
      eq(#env.messages,messages,'the same map error should not be repeated')
      eq(env.mapWrites,0); eq(env.sent,{})
    end
  end)
  test('a blocked local file and existing map metadata are both preserved',function()
    local D,env=H.reset({storage='{broken',mapUserData={[key]=sample}})
    assert(D.storageBlocked); eq(D.listRules(true),{}); eq(H.read(),'{broken')
    eq(env.mapUserData[key],sample); eq(env.mapWrites,0)
    assert(not D.mapStorage.load()); assert(not D.mapStorage.sync())
    eq(env.mapUserData[key],sample); eq(H.read(),'{broken'); eq(env.sent,{})
  end)
  test('new local edits preserve malformed or unsupported map metadata',function()
    for _,text in ipairs({'{broken','{"version":99,"enabled":true,"rules":[]}'}) do
      local D,env=H.reset({mapUserData={[key]=text}})
      assert(D.setRule(900,'Station','nw',{'say exit'}))
      eq(D.getRule(900,'nw').commands,{'say exit'}); assert(H.read())
      eq(env.mapUserData[key],text); eq(env.mapWrites,0)
      local messages=#env.messages; assert(not D.mapStorage.sync())
      eq(#env.messages,messages); eq(env.mapUserData[key],text)
      eq(env.sent,{})
    end
  end)
  test('valid local storage does not overwrite a damaged map copy',function()
    local D,env=H.reset({storage=sample,mapUserData={[key]='{damaged'}})
    eq(D.getRule(900,'nw').commands,{'say exit'}); eq(H.read(),sample)
    eq(env.mapUserData[key],'{damaged'); eq(env.mapWrites,0)
    assert(D.removeRule(900,'nw')); eq(D.getRule(900,'nw'),nil)
    eq(fromJSON(H.read()).rules,{}); eq(env.mapUserData[key],'{damaged')
    eq(env.sent,{})
  end)
  test('a failed map write retains accepted local edits and reports its error once',function()
    local D,env=H.reset(); env.mapWriteFailure='Map unavailable'
    assert(D.setRule(900,'Station','nw',{'say exit'}))
    eq(D.getRule(900,'nw').commands,{'say exit'}); assert(H.read())
    eq(env.mapUserData[key],nil)
    local messages=#env.messages; assert(not D.mapStorage.sync())
    eq(#env.messages,messages)
    env.mapWriteFailure=nil; assert(D.mapStorage.sync())
    eq(fromJSON(env.mapUserData[key]).rules[1].commands,{'say exit'})
    eq(env.sent,{})
  end)
  test('map API exceptions cannot roll back a successfully saved local edit',function()
    local D,env=H.reset(); local original=getMapUserData
    getMapUserData=function() error('Map is busy') end
    assert(D.setRule(900,'Station','nw',{'say exit'})); assert(H.read())
    eq(D.getRule(900,'nw').commands,{'say exit'})
    local messages=#env.messages; assert(not D.mapStorage.sync()); eq(#env.messages,messages)
    getMapUserData=original; assert(D.mapStorage.sync()); assert(env.mapUserData[key])
    eq(env.sent,{})
  end)
  test('map recovery adopts rules only after the local JSON save succeeds',function()
    local D,env=H.reset(); env.mapUserData[key]=sample
    local original=D.save; D.save=function() return nil,'Disk is full' end
    local ok,err=D.mapStorage.load(); assert(not ok and err)
    eq(D.listRules(true),{}); eq(D.isEnabled(),true); eq(D.storageExists,false)
    eq(H.read(),nil); eq(env.mapUserData[key],sample)
    D.save=original; assert(D.mapStorage.load())
    eq(D.getRule(900,'nw').commands,{'say exit'}); eq(D.isEnabled(),false)
    eq(env.sent,{})
  end)
  test('repeated sync avoids unchanged map writes and whole-map saves',function()
    local D,env=H.reset(); local original=saveMap
    saveMap=function() error('metadata sync must not save the whole map') end
    assert(D.setRule(900,'Station','nw',{'say exit'}))
    local writes=env.mapWrites
    assert(D.mapStorage.sync()); assert(D.mapStorage.load()); assert(D.mapStorage.sync())
    eq(env.mapWrites,writes); eq(env.sent,{})
    saveMap=original
  end)
  test('restoring map rules stops an active route before adopting disabled state',function()
    local D,env=H.reset({mapperFirst=true})
    env.exits={[100]={east=101},[101]={north=102}}
    env.room(100); env.advance(0)
    assert(D.walker.start({'e','n'},{101,102})); env.advance(0)
    eq(env.sent,{'e','n'}); assert(D.walker.active)
    env.mapUserData[key]=sample; assert(D.mapStorage.load())
    eq(D.walker.active,nil); eq(D.state.pending,nil); eq(D.isEnabled(),false)
    env.room(101); env.advance(0); env.advance(6)
    eq(env.sent,{'e','n'})
  end)
end
