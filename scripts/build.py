#!/usr/bin/env python3
"""Build a reproducible, dependency-free Mudlet package from the Lua sources."""

from __future__ import annotations

import argparse
from pathlib import Path
import xml.etree.ElementTree as ET
import zipfile


ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "lotj-doorways"
VERSION = "1.3.2"
SOURCES = ("core.lua", "map_storage.lua", "walker.lua", "ui.lua", "runtime.lua")


def package_files(root: Path = ROOT) -> dict[str, bytes]:
    """Keep the dependent modules in one script; Mudlet may reorder scripts."""
    chunks = ["-- LotJ Doorways " + VERSION + "; generated by scripts/build.py\n"]
    for name in SOURCES:
        source = (root / "src" / name).read_text(encoding="utf-8")
        chunks.append("\n-- BEGIN " + name + "\ndo\n" + source + "\nend\n")

    document = ET.Element("MudletPackage", version="1.001")
    for section in ("TriggerPackage", "TimerPackage", "AliasPackage", "ActionPackage"):
        ET.SubElement(document, section)
    scripts = ET.SubElement(document, "ScriptPackage")
    script = ET.SubElement(scripts, "Script", isActive="yes", isFolder="no")
    ET.SubElement(script, "name").text = "LotJ Doorways"
    ET.SubElement(script, "script").text = "".join(chunks)
    ET.SubElement(script, "packageName").text = PACKAGE
    ET.SubElement(script, "eventHandlerList")
    ET.SubElement(document, "KeyPackage")
    variables = ET.SubElement(document, "VariablePackage")
    ET.SubElement(variables, "HiddenVariables")
    xml = b'<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE MudletPackage>\n'
    xml += ET.tostring(document, encoding="utf-8") + b"\n"

    config = (
        'mpackage = [[lotj-doorways]]\n'
        'title = [[LotJ Doorways]]\n'
        'author = [[Quiggly-Wiggly]]\n'
        f'version = [[{VERSION}]]\n'
        'description = [[Player-defined room and direction door commands for '
        'Legends of the Jedi. Requires Mudlet 4.20+. Type doorway help after installation.]]\n'
    )
    files = {PACKAGE + ".xml": xml, "config.lua": config.encode("utf-8")}
    for name in ("README.md",):
        files[name] = (root / name).read_bytes()
    return files


def build(output: Path, root: Path = ROOT) -> Path:
    files = package_files(root)
    output.parent.mkdir(parents=True, exist_ok=True)
    # Fixed timestamps, order, permissions and compression make identical sources
    # produce byte-identical packages, independently of filesystem timestamps.
    with zipfile.ZipFile(output, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for name, data in files.items():
            entry = zipfile.ZipInfo(name, date_time=(2020, 1, 1, 0, 0, 0))
            entry.create_system = 3
            entry.external_attr = 0o100644 << 16
            entry.compress_type = zipfile.ZIP_DEFLATED
            archive.writestr(entry, data)
    return output


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "LotJ Doorways.mpackage")
    args = parser.parse_args()
    print(build(args.output).resolve())


if __name__ == "__main__":
    main()
